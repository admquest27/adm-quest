// Letras de coluna do Excel (0 -> A, 26 -> AA).
export function coluna(i) {
  let s = '';
  for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
}

// Colunas da planilha a partir da C: [{ tipo: 'hab'|'av'|'comp', comp, cod }], depois os feedbacks e o final.
export function colunasPlanilha() {
  const cols = [];
  for (const g of PLANILHA) {
    for (const h of g.habs) cols.push({ tipo: 'hab', comp: g.comp, cod: h });
    cols.push({ tipo: 'av', comp: g.comp });
    cols.push({ tipo: 'comp', comp: g.comp });
  }
  for (const c of CAMPOS_FEEDBACK) cols.push({ tipo: 'fb', id: c.id });
  cols.push({ tipo: 'final' });
  return cols;
}

